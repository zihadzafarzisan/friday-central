import { mkdir, copyFile, readdir, readFile, writeFile } from "node:fs/promises";
const source = new URL("../packages/db/migrations/", import.meta.url);
const target = new URL("../supabase/migrations/", import.meta.url);
await mkdir(target, { recursive: true });
const migrations = [];
for (const file of (await readdir(source)).filter((file) => file.endsWith(".sql")).sort()) {
  await copyFile(new URL(file, source), new URL(file, target));
  migrations.push({ file, sql: await readFile(new URL(file, source), "utf8") });
}
const tables = migrations.flatMap(({ sql }) =>
  [...sql.matchAll(/create table public\.([a-z_]+)/gi)].map((match) => match[1]),
);
if (!tables.length || new Set(tables).size !== tables.length)
  throw new Error("Unexpected migration table definitions.");
const tableArray = `array[${tables.map((table) => `'${table}'`).join(",")}]`;
const setup = `-- Generated by npm run db:prepare from packages/db/migrations. Do not edit.
-- Run once in your Supabase project's SQL Editor as the project database owner.
-- Fresh FRIDAY installation only. Existing app tables cause a safe abort.
-- This transaction creates the schema and BRACU tenant without a sample catalog.
-- Manual SQL Editor installation does not record Supabase CLI migration history.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $friday_preflight$
declare existing_table text;
begin
  if to_regclass('auth.users') is null or to_regclass('auth.identities') is null then
    raise exception 'Run this script in a Supabase project with Auth installed.';
  end if;
  select name into existing_table from unnest(${tableArray}) name
    where to_regclass('public.' || name) is not null limit 1;
  if existing_table is not null then
    raise exception 'FRIDAY setup stopped: public.% already exists. Inspect applied migrations instead of rerunning fresh setup.', existing_table;
  end if;
end $friday_preflight$;

${migrations.map(({ file, sql }) => `-- BEGIN ${file}\n${sql}\n-- END ${file}`).join("\n\n")}

-- Only the university is bootstrapped; verified programs/semesters are managed separately.
insert into public.universities(id,name,code,student_domains,timezone)
values('11111111-1111-4111-8111-111111111111','BRAC University','bracu',array['g.bracu.ac.bd'],'Asia/Dhaka');

-- Accounts may have signed into Google before these Auth triggers existed.
-- Match the same student domain as signup. Authorization still requires the
-- provider-owned Google identity via private.tenant_id(); metadata cannot grant roles.
insert into public.users(id,university_id,full_name,email,role)
select a.id,u.id,
  case when length(btrim(coalesce(a.raw_user_meta_data->>'full_name','')))>1
    then left(btrim(a.raw_user_meta_data->>'full_name'),100) else 'FRIDAY student' end,
  lower(a.email),'student'
from auth.users a cross join public.universities u
where u.code='bracu' and lower(split_part(a.email,'@',2))='g.bracu.ac.bd'
  and coalesce(a.raw_app_meta_data->>'role','student') not in ('admin','super_admin')
on conflict do nothing;
insert into public.student_profiles(user_id,university_id,student_id)
select id,university_id,null from public.users where role='student'
on conflict(user_id) do nothing;
insert into public.notification_preferences(user_id,university_id)
select id,university_id from public.users on conflict(user_id) do nothing;

notify pgrst, 'reload schema';
commit;

-- Expected: ${tables.length} tables, RLS true, one BRACU tenant. No personal records returned.
select count(*)::integer as friday_tables, bool_and(c.relrowsecurity) as all_tables_have_rls,
  (select count(*)::integer from public.universities where code='bracu') as bracu_tenants
from pg_class c join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public' and c.relname=any(${tableArray});
`;
await writeFile(new URL("../supabase/setup-friday.sql", import.meta.url), setup, "utf8");
console.log("Prepared Supabase migrations from packages/db/migrations.");
console.log(
  `Prepared supabase/setup-friday.sql: ${migrations.length} migrations, ${tables.length} tables, BRACU tenant and existing student profiles.`,
);
